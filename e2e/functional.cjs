const { appears, openApp, ok, section, today, BASE, KEY, task } = require('./harness.cjs')

module.exports = async browser => {
  section('Access: the shared link (no login screen)')
  let a = await openApp(browser, { key: null })
  ok(await a.page.getByText('Private team app').isVisible(), 'no key on the device → "Private team app" screen, not a login form')
  ok(await a.page.getByLabel('Email').count() === 0 && await a.page.getByText(/sign in|password/i).count() === 0, 'there is no email/password/sign-in anywhere')
  ok(await a.page.getByRole('link', { name: 'Outstanding' }).count() === 0 && a.requests.length === 0, 'no data is requested without a key')
  await a.page.getByLabel('Team link').fill('not a link'); await a.page.getByRole('button', { name: 'Open' }).click()
  ok(await appears(a.page.getByRole('alert').filter({ hasText: /doesn’t look like a team link/ })), 'a garbage paste is rejected with a hint')
  await a.page.getByLabel('Team link').fill(`${BASE}?k=${KEY}`); await a.page.getByRole('button', { name: 'Open' }).click()
  ok(await appears(a.page.getByRole('link', { name: 'Today', exact: true })), 'pasting the full link opens the app')
  ok(await a.page.evaluate(() => localStorage.getItem('teamKey')) === KEY, 'the key is remembered on this device')
  await a.context.close()

  a = await openApp(browser, { key: null, query: `?k=${KEY}` })
  ok(await appears(a.page.getByRole('link', { name: 'Today', exact: true })), 'opening …/?k=KEY goes straight into the app')
  ok(!a.page.url().includes('k='), 'the key is removed from the address bar after opening')
  ok(await a.page.evaluate(() => localStorage.getItem('teamKey')) === KEY, 'the key was saved from the link')
  ok(a.sent.length > 0 && a.sent.every(h => h['x-team-key'] === KEY), `the key is sent with every request (${a.sent.length} requests)`)
  await a.page.reload({ waitUntil: 'networkidle' })
  ok(await appears(a.page.getByRole('link', { name: 'Today', exact: true })), 'later visits (no key in the URL) still work on the same device')
  await a.context.close()

  a = await openApp(browser, { access: false })
  ok(await a.page.getByText('This link no longer works').isVisible(), 'a replaced/invalid key shows "This link no longer works"')
  ok(await a.page.getByRole('link', { name: 'Outstanding' }).count() === 0, 'nothing is shown for an invalid key')
  await a.context.close()
  a = await openApp(browser, { access: 'offline' })
  ok(await a.page.getByText('Can’t reach the server').isVisible() && await a.page.getByRole('button', { name: 'Try again' }).isVisible(), 'server unreachable → clear message with Try again')
  await a.context.close()

  section('Functional: everything visible and usable by everyone')
  a = await openApp(browser)
  const p = a.page
  ok((await p.title()) === 'Today · Team To-Do', 'document title follows route')
  ok(await p.getByRole('link', { name: 'Manage', exact: true }).count() === 1, 'Manage tab is available to everyone')
  ok(await p.getByText('Sign out').count() === 0, 'no sign-out (nothing to sign out of)')
  ok(await p.getByText('Follow-ups due').count() >= 1, 'follow-ups panel visible')
  ok(await p.getByText('Open Outstanding ↗').count() === 1, 'P1 task links to Outstanding')
  ok(await p.locator('.badge.tone-bad', { hasText: /Overdue \d+d/ }).count() === 1, 'overdue badge on old task')
  await p.getByRole('button', { name: 'Mark as done' }).first().click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'PATCH' && w.table === 'task_instances' && w.body.includes('Done')), 'tick marks task Done')

  await p.getByRole('link', { name: 'Outstanding', exact: true }).click(); await p.waitForSelector('table')
  ok(await p.locator('tbody tr.row-late').count() === 1, 'late row tinted')
  ok((await p.locator('tfoot').innerText()).includes('4,00,000'), 'totals footer sums balance')
  ok(await p.getByRole('button', { name: /＋ Add/ }).isVisible() && await p.getByRole('button', { name: 'Import' }).isVisible(), 'Add and Import are available')
  const clientCell = p.locator('tbody tr').first().getByLabel('Client')
  await clientCell.fill('Edited Client'); await clientCell.blur(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'PATCH' && w.table === 'outstanding' && w.body.includes('Edited Client')), 'inline edit PATCHes')
  await p.getByLabel('Open details').first().click()
  await p.getByPlaceholder('Amount received').fill('25000'); await p.getByRole('button', { name: 'Add', exact: true }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.table === 'record_payment' && w.body.includes('25000')), 'record payment RPC')
  ok(await p.getByRole('button', { name: 'Delete row' }).isVisible(), 'Delete is available in the detail panel')
  await p.keyboard.press('Escape')
  ok(await p.getByRole('dialog').count() === 0, 'Escape closes drawer')
  await p.keyboard.press('/'); await p.keyboard.type('kendra')
  ok(await p.locator('tbody tr').count() === 1, '"/" focuses search and filters')

  await p.goto(BASE + '#/tenders?status=Quoted'); await p.waitForSelector('table')
  ok((await p.getByRole('button', { name: /^Quoted/ }).getAttribute('aria-pressed')) === 'true' && await p.locator('tbody tr').count() === 1, 'deep link status filter')
  await p.getByRole('button', { name: /＋ Add/ }).click(); await p.locator('form input').first().fill('GEM/NEW'); await p.getByRole('button', { name: /Create/ }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'POST' && w.table === 'tenders' && w.body.includes('GEM/NEW')), 'add row POSTs')

  await p.goto(BASE + '#/pos'); await p.waitForSelector('table')
  ok(await p.getByText('Vendor PO Value').count() === 1 && await p.getByText('Margin', { exact: true }).count() === 1, 'vendor cost and margin columns are visible to everyone')
  await p.getByLabel('Open details').first().click()
  await p.getByRole('button', { name: /Create logistics entry/ }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.table === 'logistics' && w.body.includes('PO-1')), 'PO → logistics entry')
  ok(new URL(p.url()).hash.startsWith('#/logistics?q=PO-1'), 'navigates to logistics filtered by PO')

  await p.goto(BASE + '#/summary'); await p.waitForTimeout(400)
  ok(await p.getByText('Total margin').count() === 1, 'summary shows margin to everyone')
  ok(await p.getByRole('progressbar').count() >= 1, 'summary progress bars')
  ok(await p.locator('a[href="#/outstanding?q=GP+Kendrapada"]').count() === 1, 'top debtor deep link')
  ok(a.errors.length === 0, `no console/page errors (${a.errors.join(' | ').slice(0, 120)})`)
  await a.context.close()

  section('Functional: your name (optional, no account)')
  a = await openApp(browser)
  ok(await a.page.getByText(/set your name/i).count() >= 1, 'Today invites you to set a name')
  await a.page.getByRole('button', { name: /Set your name/ }).click()
  await a.page.getByLabel('Name as it appears in the task sheet').fill('Sagarika'); await a.page.getByRole('button', { name: 'Save' }).click()
  ok(await a.page.evaluate(() => localStorage.getItem('userName')) === 'Sagarika', 'name is saved on the device')
  await a.page.getByRole('button', { name: 'Mark as done' }).first().click(); await a.page.waitForTimeout(300)
  const withName = a.sent.filter(h => h['x-user-name'])
  ok(withName.length > 0 && Buffer.from(withName[withName.length - 1]['x-user-name'], 'base64').toString('utf8') === 'Sagarika', 'later requests carry the name (for the change history)')
  await a.page.reload({ waitUntil: 'networkidle' })
  ok(await a.page.getByLabel('Only mine').isVisible(), '"Only mine" appears once a name is set')
  ok(await a.page.getByText('Good morning, Sagarika').or(a.page.getByText(/Good (morning|afternoon|evening), Sagarika/)).first().isVisible(), 'greets by name')
  ok(await a.page.getByText('Purchase bills entry').count() === 0 || await a.page.getByText(/assigned to others/).count() >= 1, 'Only mine hides other people’s tasks and says so')
  await a.page.getByRole('button', { name: 'Sagarika' }).click(); await a.page.getByRole('button', { name: 'Clear' }).click()
  ok(await a.page.evaluate(() => localStorage.getItem('userName')) === null, 'name can be cleared')
  await a.context.close()
  a = await openApp(browser, { name: 'நிவேதா Ö' })
  await a.page.getByRole('button', { name: 'Mark as done' }).first().click(); await a.page.waitForTimeout(300)
  const h = a.sent.filter(x => x['x-user-name']).pop()
  ok(h && Buffer.from(h['x-user-name'], 'base64').toString('utf8') === 'நிவேதா Ö', 'non-English names survive the HTTP header')
  await a.context.close()

  section('Functional: Manage → sharing & history')
  a = await openApp(browser, { hash: '#/admin' })
  await a.page.getByRole('button', { name: 'Sharing' }).click()
  const link = await a.page.getByLabel('Team link').inputValue()
  ok(link.includes(`?k=${KEY}`) && link.startsWith('http'), 'Sharing shows the full link with the key')
  await a.page.getByRole('button', { name: 'Create a new link' }).click().catch(() => {})
  await a.context.close()
  a = await openApp(browser, { hash: '#/admin' })
  await a.page.getByRole('button', { name: 'Sharing' }).click()
  a.page.on('dialog', d => d.accept())
  await a.page.getByRole('button', { name: 'Create a new link' }).click(); await a.page.waitForTimeout(400)
  const rot = a.writes.find(w => w.table === 'rotate_team_key')
  ok(rot && /"new_key":"[0-9a-f]{32}"/.test(rot.body), 'creating a new link sends a fresh 128-bit key')
  const newKey = rot && JSON.parse(rot.body).new_key
  ok(await a.page.evaluate(() => localStorage.getItem('teamKey')) === newKey && (await a.page.getByLabel('Team link').inputValue()).includes(`k=${newKey}`), 'this device switches to the new link')
  await a.context.close()
  a = await openApp(browser, { hash: '#/admin' })
  await a.page.getByRole('button', { name: 'Tasks' }).click()
  await a.page.getByRole('button', { name: 'Generate today' }).click(); await a.page.waitForTimeout(300)
  ok(a.writes.some(w => w.table === 'generate_today') && await a.page.getByText('3 new task(s)').count() === 1, 'Generate today works for everyone')
  await a.page.getByRole('button', { name: '＋ Task' }).dblclick(); await a.page.waitForTimeout(300)
  ok(a.writes.filter(w => w.method === 'POST' && w.table === 'task_templates').length === 1 && a.writes.find(w => w.table === 'task_templates').body.includes('"active":false'), 'new task is created once and starts inactive')
  await a.page.getByRole('button', { name: 'History' }).click()
  ok(await appears(a.page.getByText('No changes recorded yet')), 'History tab loads')
  await a.context.close()

  section('Functional: theme')
  a = await openApp(browser, { colorScheme: 'dark' })
  const bg = async () => { await a.page.waitForTimeout(350); return a.page.evaluate(() => getComputedStyle(document.body).backgroundColor) }
  const DARK = 'rgb(11, 17, 32)'
  ok((await bg()) === DARK, 'no preference + dark OS => dark')
  await a.page.locator('[data-theme-option=light]').click()
  ok((await bg()) !== DARK && await a.page.evaluate(() => localStorage.getItem('theme')) === 'light', 'Light overrides dark OS and is saved')
  await a.page.reload({ waitUntil: 'networkidle' })
  ok(await a.page.locator('[data-theme-option=light]').getAttribute('aria-checked') === 'true', 'choice persists after reload')
  await a.page.locator('[data-theme-option=system]').click(); await a.page.emulateMedia({ colorScheme: 'light' })
  ok((await bg()) !== DARK, 'System follows OS (light)')
  await a.page.emulateMedia({ colorScheme: 'dark' })
  ok((await bg()) === DARK, 'System follows OS (dark)')
  await a.page.locator('[data-theme-option=system]').focus(); await a.page.keyboard.press('ArrowLeft')
  ok(await a.page.locator('[data-theme-option=light]').getAttribute('aria-checked') === 'true', 'arrow keys switch theme')
  await a.context.close()

  section('Functional: board & tasks')
  a = await openApp(browser, { hash: '#/board', data: { task_instances: [task(1), task(2, { status: 'Done', done_at: new Date().toISOString(), done_by_name: 'Smruti' }), task(3, { task_templates: { team: 'Tendering', title: 'BidEasy scan', freq_text: 'Daily', res1: 'Madhu', res2: null, final_res: null } })] } })
  ok(await a.page.getByText('BidEasy scan').count() === 1 && await a.page.getByText('Task 2').count() === 1, 'board lists open and done tasks')
  ok(await a.page.getByText(/done by Smruti/).count() === 1, 'shows who completed a task')
  await a.page.getByLabel('Person').fill('madhu')
  ok(await a.page.getByText('Task 1').count() === 0 && await a.page.getByText('BidEasy scan').count() === 1, 'person filter')
  await a.page.getByLabel('Person').fill('')
  const dl = a.page.waitForEvent('download'); await a.page.getByRole('button', { name: 'Export' }).click()
  ok((await dl).suggestedFilename().startsWith('Tasks-'), 'board exports Excel')
  await a.context.close()
}
