const { appears, openApp, ok, section, today, PROFILES, BASE, task } = require('./harness.cjs')

module.exports = async browser => {
  section('Functional: admin on desktop')
  let a = await openApp(browser)
  const p = a.page
  ok((await p.title()) === 'Today · Team To-Do', 'document title follows route')
  ok(await p.getByText('Follow-ups due').count() >= 1, 'follow-ups panel visible')
  ok(await p.getByText('Open Outstanding ↗').count() === 1, 'P1 task links to Outstanding')
  ok(await p.locator('.badge.tone-bad', { hasText: /Overdue \d+d/ }).count() === 1, 'overdue badge on old task')
  await p.getByRole('button', { name: 'Mark as done' }).first().click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'PATCH' && w.table === 'task_instances' && w.body.includes('Done')), 'tick marks task Done')

  await p.getByRole('link', { name: 'Outstanding', exact: true }).click(); await p.waitForSelector('table')
  ok(await p.locator('tbody tr.row-late').count() === 1, 'late row tinted')
  ok((await p.locator('tfoot').innerText()).includes('4,00,000'), 'totals footer sums balance')
  const first = p.locator('tbody tr').first()
  const clientCell = first.getByLabel('Client')
  await clientCell.fill('Edited Client'); await clientCell.blur(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'PATCH' && w.table === 'outstanding' && w.body.includes('Edited Client')), 'inline edit PATCHes')
  await p.getByLabel('Open details').first().click()
  await p.getByPlaceholder('Amount received').fill('25000'); await p.getByRole('button', { name: 'Add', exact: true }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.table === 'record_payment' && w.body.includes('25000')), 'record payment RPC')
  await p.getByPlaceholder('Amount received').fill('0'); await p.getByRole('button', { name: 'Add', exact: true }).click(); await p.waitForTimeout(250)
  ok(a.writes.filter(w => w.table === 'record_payment').length === 1, 'zero payment rejected client-side')
  await p.keyboard.press('Escape')
  ok(await p.getByRole('dialog').count() === 0, 'Escape closes drawer')
  await p.keyboard.press('/'); await p.keyboard.type('kendra')
  ok(await p.locator('tbody tr').count() === 1, '"/" focuses search and filters')

  await p.goto(BASE + '#/tenders?status=Quoted'); await p.waitForSelector('table')
  ok((await p.getByRole('button', { name: /^Quoted/ }).getAttribute('aria-pressed')) === 'true' && await p.locator('tbody tr').count() === 1, 'deep link status filter')
  await p.getByRole('button', { name: /＋ Add/ }).click(); await p.locator('form input').first().fill('GEM/NEW'); await p.getByRole('button', { name: /Create/ }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.method === 'POST' && w.table === 'tenders' && w.body.includes('GEM/NEW')), 'add row POSTs')

  await p.goto(BASE + '#/pos'); await p.waitForSelector('table')
  await p.getByLabel('Open details').first().click()
  await p.getByRole('button', { name: /Create logistics entry/ }).click(); await p.waitForTimeout(250)
  ok(a.writes.some(w => w.table === 'logistics' && w.body.includes('PO-1')), 'PO → logistics entry')
  ok(new URL(p.url()).hash.startsWith('#/logistics?q=PO-1'), 'navigates to logistics filtered by PO')

  await p.goto(BASE + '#/summary'); await p.waitForTimeout(400)
  ok(await p.getByRole('progressbar').count() >= 1, 'summary progress bars')
  ok(await p.locator('a[href="#/outstanding?q=GP+Kendrapada"]').count() === 1, 'top debtor deep link')
  await p.goto(BASE + '#/admin'); await p.waitForTimeout(300)
  await p.getByRole('button', { name: 'Users' }).click()
  ok(await appears(p.getByText('admin@co.com')), 'Admin users list shows email')
  ok(a.errors.length === 0, `no console/page errors (${a.errors.join(' | ').slice(0, 120)})`)
  await a.context.close()

  section('Functional: roles')
  a = await openApp(browser, { profile: 'admin', hash: '#/pos' }); await a.page.waitForSelector('table')
  ok(await a.page.getByText('Vendor PO Value').count() === 1 && await a.page.getByRole('link', { name: 'Admin' }).count() === 1, 'admin: sees costs and the Admin tab')
  ok(await a.page.locator('header').innerText().then(t => /Admin/.test(t) && !/Head/.test(t)), 'header shows role Admin (no Head role exists)')
  await a.page.goto(BASE + '#/admin'); await a.page.getByRole('button', { name: 'Users' }).click()
  ok(await appears(a.page.getByLabel('Role').first()) && await a.page.getByLabel('Role').first().locator('option').allInnerTexts().then(o => o.join() === 'member,admin'), 'role choices are member and admin only')
  ok(await a.page.getByLabel('Role').first().isDisabled(), 'you cannot change your own role')
  ok(await a.page.getByRole('button', { name: 'Revoke' }).first().isDisabled(), 'you cannot revoke yourself')
  await a.context.close()
  for (const [who, expectCosts, expectAdmin, expectAdd] of [['sales', false, false, true], ['logistics', false, false, false]]) {
    a = await openApp(browser, { profile: who, hash: '#/pos' }); await a.page.waitForSelector('table')
    ok((await a.page.getByText('Vendor PO Value').count() === 1) === expectCosts, `${who}: cost columns ${expectCosts ? 'visible' : 'hidden'}`)
    ok((await a.page.getByRole('link', { name: 'Admin' }).count() === 1) === expectAdmin, `${who}: Admin tab ${expectAdmin ? 'visible' : 'hidden'}`)
    ok((await a.page.getByRole('button', { name: /＋ Add/ }).count() === 1) === expectAdd, `${who}: Add button ${expectAdd ? 'shown' : 'hidden'} on POs`)
    await a.context.close()
  }

  section('Functional: pending approval')
  a = await openApp(browser, { profile: 'pending' })
  ok(await a.page.getByText('Waiting for approval').isVisible(), 'unapproved user sees waiting screen')
  ok(await a.page.getByRole('link', { name: 'Outstanding' }).count() === 0, 'no navigation for unapproved user')
  ok(a.requests.every(r => !/outstanding|tenders|po_v|po_tracker/.test(r)), 'no tracker data requested while unapproved')
  await a.context.close()
  const admin = await openApp(browser, { hash: '#/admin', data: { profiles: [PROFILES.admin, { ...PROFILES.pending, id: 'u2' }] } })
  await admin.page.getByRole('button', { name: 'Users' }).click()
  ok(await appears(admin.page.getByText('1 account(s) waiting for approval')), 'admin sees pending banner')
  await admin.page.getByRole('button', { name: 'Approve' }).click(); await admin.page.waitForTimeout(250)
  ok(admin.writes.some(w => w.table === 'profiles' && w.body.includes('"active":true')), 'Approve sends active=true')
  await admin.context.close()

  section('Functional: theme')
  a = await openApp(browser, { colorScheme: 'dark' })
  const bg = async () => { await a.page.waitForTimeout(350); return a.page.evaluate(() => getComputedStyle(document.body).backgroundColor) }
  const DARK = 'rgb(11, 17, 32)'
  ok((await bg()) === DARK, 'no preference + dark OS => dark')
  await a.page.locator('[data-theme-option=light]').click()
  ok((await bg()) !== DARK && await a.page.evaluate(() => localStorage.getItem('theme')) === 'light', 'Light overrides dark OS and is saved')
  await a.page.reload({ waitUntil: 'networkidle' })
  ok(await a.page.locator('[data-theme-option=light]').getAttribute('aria-checked') === 'true', 'choice persists after reload')
  await a.page.locator('[data-theme-option=system]').click(); await a.page.emulateMedia({ colorScheme: 'light' })
  ok((await bg()) !== DARK, 'System follows OS (light)')
  await a.page.emulateMedia({ colorScheme: 'dark' })
  ok((await bg()) === DARK, 'System follows OS (dark)')
  await a.page.locator('[data-theme-option=system]').focus(); await a.page.keyboard.press('ArrowLeft')
  ok(await a.page.locator('[data-theme-option=light]').getAttribute('aria-checked') === 'true', 'arrow keys switch theme')
  await a.context.close()

  section('Functional: board & tasks')
  a = await openApp(browser, { hash: '#/board', data: { task_instances: [task(1), task(2, { status: 'Done', done_at: new Date().toISOString() }), task(3, { task_templates: { team: 'Tendering', title: 'BidEasy scan', freq_text: 'Daily', res1: 'Madhu', res2: null, final_res: null } })] } })
  ok(await a.page.getByText('BidEasy scan').count() === 1 && await a.page.getByText('Task 2').count() === 1, 'board lists open and done tasks')
  await a.page.getByLabel('Person').fill('madhu')
  ok(await a.page.getByText('Task 1').count() === 0 && await a.page.getByText('BidEasy scan').count() === 1, 'person filter')
  await a.page.getByLabel('Person').fill('')
  const dl = a.page.waitForEvent('download'); await a.page.getByRole('button', { name: 'Export' }).click()
  ok((await dl).suggestedFilename().startsWith('Tasks-'), 'board exports Excel')
  await a.context.close()
}
